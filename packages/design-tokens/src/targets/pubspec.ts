import { WEIGHT_FILE_SUFFIX } from "../format.ts";
import type { DesignTokens, FontKey } from "../tokens.ts";

export const PUBSPEC_BEGIN = "  # BEGIN design-tokens:fonts (generated by @chicman/design-tokens — run `pnpm tokens`)";
export const PUBSPEC_END = "  # END design-tokens:fonts";

/** Font asset paths (relative to apps/mobile) required by the tokens. */
export function fontAssets(tokens: DesignTokens): string[] {
  return (Object.keys(tokens.font) as FontKey[]).flatMap((key) => {
    const font = tokens.font[key];
    return font.weights.map(
      (w) => `assets/fonts/${font.flutterAssetPrefix}-${WEIGHT_FILE_SUFFIX[w]}.ttf`,
    );
  });
}

/** Flutter output: the `fonts:` block of pubspec.yaml, between the markers. */
export function renderPubspecFonts(tokens: DesignTokens): string {
  const lines = [PUBSPEC_BEGIN, "  # Font files are SIL OFL 1.1; licenses are in assets/fonts/.", "  fonts:"];
  for (const key of Object.keys(tokens.font) as FontKey[]) {
    const font = tokens.font[key];
    lines.push(`    - family: ${font.flutterFamily}`, "      fonts:");
    for (const w of font.weights) {
      lines.push(
        `        - asset: assets/fonts/${font.flutterAssetPrefix}-${WEIGHT_FILE_SUFFIX[w]}.ttf`,
        `          weight: ${w}`,
      );
    }
  }
  lines.push(PUBSPEC_END);
  return lines.join("\n");
}

/** Replace the marked region of an existing pubspec.yaml. */
export function applyPubspecFonts(pubspec: string, block: string): string {
  const start = pubspec.indexOf(PUBSPEC_BEGIN);
  const end = pubspec.indexOf(PUBSPEC_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(
      "apps/mobile/pubspec.yaml is missing the design-tokens font markers.\n" +
        `Add these two lines inside the \`flutter:\` section:\n${PUBSPEC_BEGIN}\n${PUBSPEC_END}`,
    );
  }
  return pubspec.slice(0, start) + block + pubspec.slice(end + PUBSPEC_END.length);
}
